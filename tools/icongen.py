"""Generates Ondalune's adaptive launcher icons: a crescent moon cradling a five-bar waveform.
Writes VectorDrawable layers, adaptive-icon XML, legacy PNG mipmaps (via rsvg-convert) and
preview PNGs.

usage: python3 tools/icongen.py <res_dir> <out_dir>
"""
import math
import os
import subprocess
import sys

RES, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)


# ---------------------------------------------------------------- geometry (108 x 108 viewport)
def crescent(cx, cy, R, ix, iy, r):
    """Outer circle (cx,cy,R) minus inner circle (ix,iy,r), opening towards the inner circle."""
    dx, dy = ix - cx, iy - cy
    d = math.hypot(dx, dy)
    a = (R * R - r * r + d * d) / (2 * d)
    h = math.sqrt(R * R - a * a)
    mx, my = cx + a * dx / d, cy + a * dy / d
    p1 = (mx - h * dy / d, my + h * dx / d)
    p2 = (mx + h * dy / d, my - h * dx / d)
    f = lambda p: f"{p[0]:.2f},{p[1]:.2f}"
    return f"M{f(p1)} A{R},{R} 0 1,1 {f(p2)} A{r},{r} 0 1,0 {f(p1)} Z"


def pill(cx, cy, w, h):
    """Vertical rounded bar."""
    r = w / 2
    top, bottom = cy - h / 2 + r, cy + h / 2 - r
    return (f"M{cx - r:.2f},{top:.2f} A{r},{r} 0 0,1 {cx + r:.2f},{top:.2f} L{cx + r:.2f},{bottom:.2f} "
            f"A{r},{r} 0 0,1 {cx - r:.2f},{bottom:.2f} Z")


MOON = crescent(51.8, 54.0, 25.9, 61.2, 49.0, 20.9)
BARS = " ".join(pill(62.6 + (i - 2) * 5.6, 51.5, 3.4, hgt) for i, hgt in enumerate([7.5, 13.0, 20.0, 13.0, 7.5]))
# Soft waves washing over the lower part of the moon, clipped to it.
WAVE_1 = "M18,49 C26,59 38,66 52,69.5 C64,72 76,70 88,62 L88,98 L18,98 Z"
WAVE_2 = "M18,61 C27,71 40,77.5 54,79 C66,80 77,76 88,69 L88,98 L18,98 Z"

# name: (background stops top->bottom, glyph colour or None for the shaded moon, label)
VARIANTS = {
    "moonlight": (["#1D1D20", "#0B0B0C"], None),
    "paper": (["#F5F5F3", "#ECECEA"], "#0E0E10"),
    "slate": (["#CFD0D3", "#C2C3C7"], "#2A2B2F"),
    "graphite": (["#34353A", "#2A2B2F"], "#A3A4A9"),
}
ORDER = ["moonlight", "paper", "slate", "graphite"]

# ---------------------------------------------------------------- VectorDrawable output
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icongen.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        'xmlns:aapt="http://schemas.android.com/aapt" android:width="108dp" android:height="108dp" '
        'android:viewportWidth="108" android:viewportHeight="108">\n')


def lin(stops, x1, y1, x2, y2):
    items = "".join(f'<item android:offset="{i / (len(stops) - 1):.2f}" android:color="{c}" />' for i, c in enumerate(stops))
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
            f'android:endX="{x2}" android:endY="{y2}">{items}</gradient></aapt:attr>')


def path(d, fill=None, alpha=None, inner=""):
    a = f' android:fillAlpha="{alpha}"' if alpha is not None else ""
    fc = f' android:fillColor="{fill}"' if fill else ""
    return f'  <path android:pathData="{d}"{fc}{a}>{inner}</path>\n'


def write(p, text):
    with open(p, "w") as fh:
        fh.write(text)


def vd_layers(name, bg, glyph):
    background = HEAD + path("M0,0h108v108h-108z", inner=lin(bg, 0, 0, 0, 108))
    if glyph is None:
        # A faint glow behind the moon so it lifts off the black.
        background += ('  <path android:pathData="M0,0h108v108h-108z"><aapt:attr name="android:fillColor">'
                       '<gradient android:type="radial" android:centerX="50" android:centerY="50" android:gradientRadius="40">'
                       '<item android:offset="0" android:color="#1FFFFFFF" /><item android:offset="1" android:color="#00FFFFFF" />'
                       '</gradient></aapt:attr></path>\n')
    write(f"{RES}/drawable/ic_launcher_bg_{name}.xml", background + "</vector>\n")

    fg = HEAD
    if glyph is None:
        fg += path(MOON, inner=lin(["#FFFFFF", "#F1F1F4"], 30, 30, 60, 80))
        fg += (f'  <group>\n    <clip-path android:pathData="{MOON}" />\n'
               f'  {path(WAVE_1, inner=lin(["#DEDEE3", "#C9C9CF"], 20, 55, 80, 80))}'
               f'  {path(WAVE_2, inner=lin(["#B8B8BF", "#9C9CA4"], 20, 65, 80, 90))}  </group>\n')
        fg += path(BARS, inner=lin(["#FFFFFF", "#E6E6EA"], 60, 40, 60, 62))
    else:
        fg += path(MOON, glyph) + path(BARS, glyph)
    write(f"{RES}/drawable/ic_launcher_fg_{name}.xml", fg + "</vector>\n")


def adaptive(name, mip):
    s = ('<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
         f'    <background android:drawable="@drawable/ic_launcher_bg_{name}" />\n'
         f'    <foreground android:drawable="@drawable/ic_launcher_fg_{name}" />\n'
         '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n')
    write(f"{RES}/mipmap-anydpi-v26/{mip}.xml", s)
    write(f"{RES}/mipmap-anydpi-v26/{mip}_round.xml", s)


# ---------------------------------------------------------------- SVG (legacy PNGs + previews)
def svg_body(bg, glyph):
    def g(gid, stops, x1, y1, x2, y2):
        st = "".join(f'<stop offset="{i / (len(stops) - 1):.2f}" stop-color="{c}"/>' for i, c in enumerate(stops))
        return f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}">{st}</linearGradient>'
    defs = g("bg", bg, 0, 0, 0, 108)
    body = '<rect width="108" height="108" fill="url(#bg)"/>'
    if glyph is None:
        defs += ('<radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="50" cy="50" r="40">'
                 '<stop offset="0" stop-color="#fff" stop-opacity="0.12"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>')
        defs += g("moon", ["#FFFFFF", "#F1F1F4"], 30, 30, 60, 80) + g("w1", ["#DEDEE3", "#C9C9CF"], 20, 55, 80, 80)
        defs += g("w2", ["#B8B8BF", "#9C9CA4"], 20, 65, 80, 90) + g("bars", ["#FFFFFF", "#E6E6EA"], 60, 40, 60, 62)
        defs += f'<clipPath id="moonclip"><path d="{MOON}"/></clipPath>'
        body += '<rect width="108" height="108" fill="url(#glow)"/>'
        body += f'<path d="{MOON}" fill="url(#moon)"/>'
        body += f'<g clip-path="url(#moonclip)"><path d="{WAVE_1}" fill="url(#w1)"/><path d="{WAVE_2}" fill="url(#w2)"/></g>'
        body += f'<path d="{BARS}" fill="url(#bars)"/>'
    else:
        body += f'<path d="{MOON}" fill="{glyph}"/><path d="{BARS}" fill="{glyph}"/>'
    return defs, body


def svg_doc(defs, body, clip):
    c = '<circle cx="54" cy="54" r="36"/>' if clip == "round" else '<rect x="18" y="18" width="72" height="72" rx="16"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><defs>{defs}<clipPath id="c">{c}</clipPath></defs>'
            f'<g clip-path="url(#c)">{body}</g></svg>')


write(f"{RES}/drawable/ic_launcher_monochrome.xml", HEAD + path(MOON, "#FFFFFF") + path(BARS, "#FFFFFF") + "</vector>\n")

DENS = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
for name in ORDER:
    bg, glyph = VARIANTS[name]
    vd_layers(name, bg, glyph)
    defs, body = svg_body(bg, glyph)
    mip = "ic_launcher" if name == "moonlight" else f"ic_launcher_{name}"
    adaptive(name, mip)
    for clip, suffix in (("square", ""), ("round", "_round")):
        sp = f"{OUT}/{name}{suffix}.svg"
        write(sp, svg_doc(defs, body, clip))
        for dname, px in DENS.items():
            subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), sp, "-o", f"{RES}/mipmap-{dname}/{mip}{suffix}.png"], check=True)
    subprocess.run(["rsvg-convert", "-w", "256", "-h", "256", f"{OUT}/{name}.svg", "-o", f"{OUT}/{name}.png"], check=True)
# Full-bleed 512px store icon (no mask) for the README and store metadata.
d, b = svg_body(*VARIANTS["moonlight"])
write(f"{OUT}/store_icon.svg", f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><defs>{d}</defs>{b}</svg>')
subprocess.run(["rsvg-convert", "-w", "512", "-h", "512", f"{OUT}/store_icon.svg", "-o", f"{OUT}/store_icon.png"], check=True)
print("ok")
